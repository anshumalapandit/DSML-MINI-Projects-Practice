# (B) Fill missing numeric columns with mean
num_cols = df.select_dtypes(include=[np.number]).columns
for col in num_cols:
    df[col] = df[col].fillna(df[col].mean())

# (C) Fill missing categorical columns with mode
cat_cols = df.select_dtypes(include=["object"]).columns
for col in cat_cols:
    df[col] = df[col].fillna(df[col].mode()[0])

print("\nAfter Filling Missing Values:")
print(df.isnull().sum())


# (D) Remove duplicate rows (if any)
df = df.drop_duplicates()
print("\nAfter Removing Duplicates:")
print(df)


# ------------------ 3) DATA TRANSFORMATION ------------------

# (A) Convert categorical to category-type
if "Age" in df.columns:
    df["Age"] = df["Age"].astype("category")

# (B) One-hot encoding (dummy variables)
df_dummies = pd.get_dummies(df, drop_first=True)
print("\nAfter One-Hot Encoding:")
print(df_dummies.head())

# (C) Normalize numeric columns (Min-Max scaling)
for col in num_cols:
    df_dummies[col+"_scaled"] = (df_dummies[col] - df_dummies[col].min()) / (df_dummies[col].max() - df_dummies[col].min())

