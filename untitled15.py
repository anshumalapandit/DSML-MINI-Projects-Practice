# STEP 1: Frequency table
freq = pd.crosstab(df["Age"], df["Class"])
print("Frequency Table:\n", freq, "\n")

# Entropy function
def entropy(col):
    probs = col.value_counts(normalize=True)
    return -(probs * np.log2(probs)).sum()

# STEP 2: Parent entropy
entropy_full = entropy(df["Class"])
print("Entropy of Full Dataset:", entropy_full, "\n")

# STEP 3: Entropy of each Age group
entropy_young = entropy(df[df["Age"]=="Young"]["Class"])
